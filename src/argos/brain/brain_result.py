"""BrainResult data transfer object.

Defines the final compiled outcome container for the ARGOS Brain Core,
aggregating telemetry, decision histories, and execution outputs.
"""

from dataclasses import dataclass, field
from typing import Any

from argos.brain.brain_status import BrainStatus
from argos.brain.constants import DEFAULT_BRAIN_ENGINE
from argos.execution.execution_result import ExecutionResult
from argos.input.parsed_request import ParsedRequest
from argos.intent.intent_result import IntentResult
from argos.planning.plan import Plan


@dataclass(slots=True)
class BrainResult:
    """Compiled outcome container for the ARGOS Brain Core.

    Attributes:
        parsed_request: Normalized and parsed request from input processing.
        intent_result: Semantic classification and entity extraction output.
        plan: Structured action recipe generated by the planning layer.
        execution_result: Outcome compiled by the execution subsystem.
        decision_history: Sequential trace of cognitive decisions taken.
        final_goal: Identifier or description of the primary session goal.
        brain_status: High-level lifecycle outcome of the cognitive loop.
        brain_engine: Identifier of the brain engine that processed the session.
        metadata: Optional telemetry, timing, and diagnostic metadata.
    """

    parsed_request: ParsedRequest | None = None
    intent_result: IntentResult | None = None
    plan: Plan | None = None
    execution_result: ExecutionResult | None = None
    decision_history: list[str] = field(default_factory=list)
    final_goal: str = "unknown"
    brain_status: BrainStatus = BrainStatus.IDLE
    brain_engine: str = DEFAULT_BRAIN_ENGINE
    metadata: dict[str, Any] = field(default_factory=dict)
